import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
test('MI002 opens from existing CAD app with two traced panels and no source-book method',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'MI-002 — short de elástico simples'}).click();
 await expect(page.getByTestId('mi002-workspace')).toBeVisible();
 const viewport=page.getByTestId('mi002-svg-viewport');
 await expect(viewport.locator('g#FRONT')).toHaveCount(1);
 await expect(viewport.locator('g#BACK')).toHaveCount(1);
 await expect(page.getByRole('status')).toContainText('DRAFT / NO CUT');
 await expect(page.getByTestId('mi002-edge-FRONT:E06')).toContainText('UNCLASSIFIED');
 await expect(page.getByTestId('mi002-edge-FRONT:E07')).toContainText('CONSTRUCTION_LINE');
 await expect(page.getByText('cutReady:')).toBeVisible();
 await expect(page.getByText('NOT_RUN',{exact:true}).first()).toBeVisible();
});
test('MI002 edits measures in cm, saves mm values, validates reload and never creates allowances automatically',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'MI-002 — short de elástico simples'}).click();
 await page.getByRole('spinbutton',{name:'Quadril'}).fill('106');
 await page.getByRole('spinbutton',{name:'Quadril'}).blur();
 await expect(page.getByText(/Revisão 1/)).toBeVisible();
 await expect(page.getByTestId('mi002-diagnostic')).toContainText('entreperna 120.00 mm');
 const [d]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Salvar projeto MI-002'}).click()]);
 const json=await readFile(await d.path(),'utf8'),p=JSON.parse(json);
 expect(p.measurements.hip).toBe(1060);expect(p.revision).toBe(1);
 expect(p.pieces.map((x:{id:string})=>x.id)).toEqual(['FRONT','BACK']);
 expect(p.pieces.every((x:{edges:{allowanceMm:number|null}[]})=>x.edges.every(e=>e.allowanceMm===null))).toBe(true);
 expect(p.release).toEqual({cutReady:false,scalePhysical:'NOT_RUN',assembly:'NOT_RUN',fit:'NOT_RUN'});
 await page.getByRole('button',{name:'Reiniciar exemplo'}).click();
 await page.locator('input[type=file]').setInputFiles({name:'short.draft.json',mimeType:'application/json',buffer:Buffer.from(json)});
 await expect(page.getByText(/Revisão 1/)).toBeVisible();
 await expect(page.getByRole('spinbutton',{name:'Quadril'})).toHaveValue('106');
});
test('MI002 downloads exact size A4 PDF, vector SVG, page map and lengths with no production flag',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'MI-002 — short de elástico simples'}).click();
 const [mapFile]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Mapa A4 de montagem'}).click()]);
 const map=JSON.parse(await readFile(await mapFile.path(),'utf8'));
 expect(map.tiles.length).toBeGreaterThan(2);
 expect(map.metadata.commitSha).toMatch(/^[0-9a-f]{40}$/);
 expect(map.tiles.some((x:{neighbors:{right:number|null}})=>x.neighbors.right!==null)).toBe(true);
 expect(map.release.scalePhysical).toBe('NOT_RUN');
 const [pdfFile]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Exportar PDF A4 paginado 100%'}).click()]);
 const pdf=(await readFile(await pdfFile.path())).toString('utf8');
 expect(pdf).toContain('DRAFT / NO CUT / PROVISIONAL GEOMETRY');
 expect(pdf).toContain('/Count '+map.tiles.length);
 expect(pdf).toContain(map.metadata.commitSha);
 const [svgFile]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Exportar SVG 1:1'}).click()]);
 const svg=await readFile(await svgFile.path(),'utf8');
 expect(svg).toContain('FRONT:E06');expect(svg).toContain('BACK:E06');
 expect(svg).not.toContain('data-classification="CUT_LINE"');
 const [diagFile]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Diagnóstico de comprimentos JSON'}).click()]);
 const diag=JSON.parse(await readFile(await diagFile.path(),'utf8'));
 expect(diag.pieces).toHaveLength(2);
 expect(diag.pieces[0].waistMm).toBe(225);
 expect(diag.release.cutReady).toBe(false);
});
